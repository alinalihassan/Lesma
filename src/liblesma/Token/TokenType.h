#pragma once

#include <cstdint>
namespace lesma {

enum class TokenType : std::uint8_t {
  // Whitespace
  NEWLINE,
  LINE_COMMENT,
  BLOCK_COMMENT,

  // Single-character tokens.
  LEFT_PAREN,
  RIGHT_PAREN,
  LEFT_BRACE,
  RIGHT_BRACE,
  LEFT_SQUARE,
  RIGHT_SQUARE,
  COLON,
  ARROW,
  FAT_ARROW,
  COMMA,
  DOT,
  MINUS,
  PLUS,
  SEMICOLON,
  SLASH,
  STAR,
  MOD,
  POWER,
  XOR,
  AMPERSAND,
  TILDE,
  RANGE,
  ELLIPSIS,
  PIPE,
  QUESTION,
  NULL_COALESCE,

  // One or two character tokens.
  BANG,
  BANG_EQUAL,
  EQUAL,
  EQUAL_EQUAL,
  GREATER,
  GREATER_EQUAL,
  LESS,
  LESS_EQUAL,

  PLUS_EQUAL,
  MINUS_EQUAL,
  SLASH_EQUAL,
  STAR_EQUAL,
  MOD_EQUAL,
  POWER_EQUAL,
  XOR_EQUAL,
  AMPERSAND_EQUAL,
  PIPE_EQUAL,
  SHIFT_LEFT,
  SHIFT_LEFT_EQUAL,
  SHIFT_RIGHT,
  SHIFT_RIGHT_EQUAL,
  NULL_COALESCE_EQUAL,

  // Literals.
  IDENTIFIER,
  STRING,
  /** Decoded UTF-8 chunk inside an interpolated string literal `"a${...}b"`. */
  STRING_TEMPLATE_CHUNK,
  STRING_TEMPLATE_EXPR_START,
  STRING_TEMPLATE_EXPR_END,
  INTEGER,
  DOUBLE,
  BOOL,

  // Types
  INT_TYPE,
  FLOAT_TYPE,
  STRING_TYPE,
  BOOL_TYPE,
  VOID_TYPE,
  FUNC_TYPE,
  PTR_TYPE,
  LIST_TYPE,
  CUSTOM_TYPE,
  INT8_TYPE,
  INT16_TYPE,
  INT32_TYPE,
  UINT_TYPE,
  UINT8_TYPE,
  UINT16_TYPE,
  UINT32_TYPE,
  FLOAT32_TYPE,
  ANY_TYPE,
  /** Structural tuple type `(T1, T2, ...)` in TypeExpr; not a lexer token. */
  TUPLE_TYPE,
  /** Structural union type `T1 | T2 | ...` in TypeExpr; not a lexer token. */
  UNION_TYPE,

  // Keywords.
  AND,
  CLASS,
  ENUM,
  ELSE,
  ELSE_IF,
  FALSE_,
  FOR,
  FUNC,
  IF,
  NIL,
  OR,
  NOT,
  EXTERN,
  EXPORT,
  OPERATOR,
  RETURN,
  SUPER,
  THIS,
  TRUE_,
  VAR,
  LET,
  WHILE,
  BREAK,
  CONTINUE,
  PASS,
  DEFER,
  AS,
  IS,
  IS_NOT,
  IN,
  IMPORT,
  FROM,
  TRAIT,
  IMPL,
  PRIVATE,
  OVERLOAD,
  STATIC,

  // Special tokens
  EOF_TOKEN,
  NULL_TOKEN,
};
}